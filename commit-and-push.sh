#!/bin/bash

# Скрипт для коммита и пуша всех изменений в GitHub

echo "📦 Коммит и пуш изменений в GitHub..."
echo ""

# Проверяем, инициализирован ли git
if [ ! -d ".git" ]; then
    echo "❌ Git репозиторий не инициализирован!"
    echo ""
    echo "Сначала выполните:"
    echo "  ./git-init.sh"
    exit 1
fi

# Проверяем, есть ли remote
if ! git remote | grep -q "origin"; then
    echo "❌ Remote 'origin' не настроен!"
    echo ""
    echo "Сначала выполните:"
    echo "  git remote add origin <your-github-repo-url>"
    exit 1
fi

# Добавляем все изменения
echo "📝 Добавление всех изменений..."
git add .

# Проверяем, есть ли изменения для коммита
if git diff --staged --quiet; then
    echo "ℹ️  Нет изменений для коммита"
    exit 0
fi

# Показываем статистику изменений
echo ""
echo "📊 Статистика изменений:"
git diff --staged --stat
echo ""

# Создаем коммит
echo "💾 Создание коммита..."
git commit -m "✨ Расширенные демо-данные и улучшения

- Добавлены 3 пользователя (Иван, Мария, Алексей Петровы)
- Расширено до 5 счетов (наличные, карта, накопительный, кредитный, валютный)
- Увеличено до 15 категорий расходов и доходов
- Создано 150 транзакций за последние 3 месяца
- Добавлено 80 чеков с позициями товаров
- Настроено 10 бюджетов по категориям
- Добавлено 10 регулярных платежей
- Создана подробная документация DEMO_DATA.md
- Обновлен README.md с информацией о демо-данных
- Улучшена работа с чеками в offline режиме
- Убран offline режим, приложение работает только онлайн
- Исправлены ошибки TypeScript и сборки

📊 Демо-данные теперь включают:
- 3 члена семьи
- 5 счетов с общим балансом ~710,000₽
- 15 категорий
- 150 транзакций
- 80 чеков
- 10 бюджетов (111,000₽/месяц)
- 10 регулярных платежей

🔧 Технические изменения:
- Упрощена архитектура (только онлайн режим)
- Улучшена обработка чеков
- Добавлены демо-данные в server/index.js
- Создана документация по демо-данным"

# Пушим в GitHub
echo ""
echo "📤 Пуш в GitHub..."
git push origin main

echo ""
echo "✅ Готово! Все изменения запушены в GitHub"
echo ""
echo "🌐 Проверьте свой репозиторий на GitHub"
