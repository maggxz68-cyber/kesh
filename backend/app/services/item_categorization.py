def categorize_item(item_name: str) -> str:
    """
    Определяет категорию товара по его названию.
    Возвращает название категории или 'Продукты' по умолчанию для нераспознанных товаров 
    (так как большинство нераспознанных товаров в чеках супермаркетов — это всё же продукты).
    """
    if not item_name:
        return "Продукты"
    
    name_lower = item_name.lower()
    
    # Сначала проверяем строгие категории (Алкоголь, Химия, Авто и т.д.)
    strict_categories = ["Алкоголь", "Еда вне дома", "Бытовая химия и гигиена", "Аптека и здоровье", "Авто"]
    for category in strict_categories:
        if any(keyword in name_lower for keyword in CATEGORY_KEYWORDS[category]):
            return category
            
    # Если не попало в строгие категории, проверяем "Продукты"
    if any(keyword in name_lower for keyword in CATEGORY_KEYWORDS["Продукты"]):
        return "Продукты"
        
    # Умный фоллбэк: если товар не распознан, но это явно не спец. категория, 
    # скорее всего это какой-то специфический продукт питания.
    return "Продукты"
