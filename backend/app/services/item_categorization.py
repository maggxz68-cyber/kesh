"""Эвристическая категоризация товаров по названию."""
import logging

logger = logging.getLogger(__name__)

# Словарь ключевых слов -> Категория
# Можно легко расширять по мере необходимости
CATEGORY_KEYWORDS = {
    "Еда вне дома": ["бургер", "пицца", "суши", "ролл", "шаурма", "кофе", "чай", "напиток", "латте", "капучино", "воппер", "чизбургер", "картошка фри", "морс", "лимонад"],
    "Продукты": ["молоко", "хлеб", "сыр", "яйца", "колбаса", "мясо", "овощи", "фрукты", "вода", "шоколад", "печенье", "йогурт", "творог", "масло", "сахар", "мука", "макароны", "гречка", "рис", "сок"],
    "Бытовая химия и гигиена": ["шампунь", "мыло", "зубная", "паста", "порошок", "туалет", "гель", "крем", "бумага", "полотенца", "средство", "чистящее"],
    "Аптека и здоровье": ["витамин", "аспирин", "пластырь", "антисептик", "маска", "термометр", "мазь"],
    "Авто": ["бензин", "дизель", "масло", "омывай", "антифриз", "фильтр"],
    "Алкоголь": ["пиво", "водка", "вино", "коньяк", "виски", "сидр"]
}

def categorize_item(item_name: str) -> str:
    """
    Определяет категорию товара по его названию.
    Возвращает название категории или 'Разное', если совпадений нет.
    """
    if not item_name:
        return "Разное"
    
    name_lower = item_name.lower()
    
    for category, keywords in CATEGORY_KEYWORDS.items():
        if any(keyword in name_lower for keyword in keywords):
            return category
            
    return "Разное"
